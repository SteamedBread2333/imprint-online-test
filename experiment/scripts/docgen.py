def build_md(title, domain, sections):
    lines = [f"# {title}", ""]
    lines.append(f"下列条文是 aurora 服务（Python FastAPI）在「{domain}」方面的唯一权威来源，"
                 f"供协作与检索使用。每节首句为结论，后文为展开。")
    lines.append("")
    for heading, answer in sections:
        lines.append(f"## {heading}")
        lines.append("")
        lines.append(expand(answer, heading, domain))
        lines.append("")
    return "\n".join(lines)


def main():
    os.makedirs(DOCS_DIR, exist_ok=True)
    for fn, title, domain, sections in DOCS:
        path = os.path.join(DOCS_DIR, fn)
        with open(path, "w", encoding="utf-8") as f:
            f.write(build_md(title, domain, sections))
        n = sum(len(expand(a, h, domain)) + len(h) for h, a in sections)
        print(f"wrote {fn:24s} {len(sections)} sections, ~{n} chars, "
              f"{os.path.getsize(path)} bytes")


if __name__ == "__main__":
    main()